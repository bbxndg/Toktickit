import { test, expect, type Page } from '@playwright/test';

async function login(page: Page, role: 'REQUESTER' | 'IT_STAFF') {
  const email = process.env[`E2E_${role}_EMAIL`];
  if (!email || !process.env.E2E_PASSWORD || !process.env.E2E_TICKET_NUMBER) throw Error('Run using the isolated E2E runner.');
  await page.goto('/');
  await page.getByLabel('Email Address').fill(email);
  await page.getByLabel('Password', { exact: true }).fill(process.env.E2E_PASSWORD);
  await page.getByRole('button', { name: 'Sign In' }).click();
  await expect(page.getByRole('heading', { name: 'Dashboard' })).toBeVisible();
  await page.getByRole('button', { name: `Open ${process.env.E2E_TICKET_NUMBER}`, exact: true }).click();
}

test('staff records work, resolves the gate and requester reads the result', async ({ page }, info) => {
  await login(page, 'IT_STAFF');
  await page.getByRole('button', { name: 'Actions Taken', exact: true }).click();
  const addAction = page.getByRole('button', { name: 'Add Action' });
  await addAction.click();
  const dialog = page.getByRole('dialog', { name: 'Create Action' });
  await expect(dialog.getByRole('button', { name: 'Close dialog' })).toBeFocused();
  await page.keyboard.press('Shift+Tab');
  await expect(dialog.getByRole('button', { name: 'Save Action' })).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(dialog.getByRole('button', { name: 'Close dialog' })).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(dialog).toHaveCount(0);
  await expect(addAction).toBeFocused();
  await addAction.click();
  await page.getByRole('button', { name: 'Save Action' }).click();
  await expect(page.getByLabel('Action Description')).toHaveAttribute('aria-invalid', 'true');
  await page.getByLabel('Action Description').fill('Investigate browser workflow fixture');
  await page.getByRole('button', { name: 'Save Action' }).click();
  const actionRow = page.locator('tr').filter({ hasText: 'Investigate browser workflow fixture' });
  await expect(actionRow).toBeVisible();
  await expect(page.getByText('Complete or cancel pending actions before resolving this ticket.')).toBeVisible();
  await page.screenshot({ path: info.outputPath('resolution-gate.png'), fullPage: true });
  await actionRow.getByRole('button', { name: 'Edit' }).click();
  await page.getByLabel('Status', { exact: true }).selectOption('COMPLETED');
  await page.getByLabel('Result').fill('Verified the problem was fixed.');
  await page.getByRole('button', { name: 'Save Changes' }).click();
  await page.getByRole('button', { name: 'Confirm Completion' }).click();
  await expect(actionRow.getByText('Completed')).toBeVisible();
  await actionRow.getByRole('button', { name: 'View' }).click();
  await expect(page.getByRole('dialog', { name: 'View Action' })).toContainText('Verified the problem was fixed.');
  await page.screenshot({ path: info.outputPath('completed-action-view.png'), fullPage: true });
  await page.getByRole('dialog', { name: 'View Action' }).getByRole('button', { name: 'Close', exact: true }).click();
  await expect(page.getByText('Complete or cancel pending actions before resolving this ticket.')).toHaveCount(0);
  await addAction.click();
  await page.getByLabel('Action Description').fill('Unneeded follow-up');
  await page.getByRole('button', { name: 'Save Action' }).click();
  const cancelledRow = page.locator('tr').filter({ hasText: 'Unneeded follow-up' });
  await cancelledRow.getByRole('button', { name: 'Edit' }).click();
  await page.getByLabel('Status', { exact: true }).selectOption('CANCELLED');
  await page.getByLabel('Cancellation Reason').fill('No longer required.');
  await page.getByRole('button', { name: 'Save Changes' }).click();
  await page.getByRole('button', { name: 'Confirm Cancellation' }).click();
  await expect(cancelledRow.getByText('Cancelled')).toBeVisible();
  const transition = page.getByTestId('status-transition-select');
  await transition.selectOption('IN_PROGRESS');
  await expect(transition).toHaveValue('IN_PROGRESS');
  await page.getByRole('button', { name: /Sign Out/ }).click();
  await login(page, 'REQUESTER');
  await page.getByTestId('indicate-resolved-btn').click();
  await page.getByTestId('confirm-resolve-btn').click();
  await expect(page.getByText('Sent to IT for review').first()).toBeVisible();
  await page.screenshot({ path: info.outputPath('requester-indication.png'), fullPage: true });
  await page.getByRole('button', { name: /Sign Out/ }).click();
  await login(page, 'IT_STAFF');
  await expect(page.getByText('Requester reports that the problem appears resolved.')).toBeVisible();
  await transition.selectOption('RESOLVED');
  await page.getByLabel('Resolution Summary').fill('Verified the problem was fixed.');
  await page.getByRole('button', { name: 'Confirm & Update Status' }).click();
  await expect(transition).toHaveValue('RESOLVED');
  await transition.selectOption('REOPENED');
  await expect(transition).toHaveValue('REOPENED');
  await expect(page.getByText('Requester reports that the problem appears resolved.')).toHaveCount(0);
  await transition.selectOption('RESOLVED');
  await page.getByLabel('Resolution Summary').fill('Rechecked and resolved again.');
  await page.getByRole('button', { name: 'Confirm & Update Status' }).click();
  await expect(transition).toHaveValue('RESOLVED');
  await transition.selectOption('CLOSED');
  await page.getByRole('button', { name: 'Confirm & Update Status' }).click();
  await expect(transition).toHaveValue('CLOSED');
  await page.getByRole('button', { name: 'Status History' }).click();
  await expect(page.getByRole('region', { name: 'Status History' })).toContainText('Closed');
  await page.screenshot({ path: info.outputPath('status-history.png'), fullPage: true });
  await page.getByRole('button', { name: /Sign Out/ }).click();
  await login(page, 'REQUESTER');
  await page.getByRole('button', { name: 'Actions Taken', exact: true }).click();
  await expect(page.getByText('Investigate browser workflow fixture').first()).toBeVisible();
  await expect(page.getByRole('button', { name: 'Add Action' })).toHaveCount(0);
  await page.screenshot({ path: info.outputPath('requester-readonly.png'), fullPage: true });
});
