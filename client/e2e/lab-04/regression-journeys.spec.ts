  test(`assignee failure, HTTP 400/500/422, reviewed retry and busy guard at ${viewport.width}px`, async ({ page }, info) => {
    test.setTimeout(60000); await page.setViewportSize(viewport);
    const requester = await db.user.findUniqueOrThrow({ where: { email: process.env.E2E_REQUESTER_EMAIL! } });
    const category = await db.category.findFirstOrThrow(), system = await db.relatedSystem.findFirstOrThrow();
    const ticket = await db.ticket.create({ data: { ticketNumber: `ERROR-${randomUUID()}`, summary: 'Browser error recovery fixture',
      description: 'Synthetic API failures followed by a real successful save', requestedPriority: 'HIGH', requesterId: requester.id,
      categoryId: category.id, relatedSystemId: system.id } });
    ticketIds.push(ticket.id);
    let membersAvailable = false;
    await page.route('**/api/staff/members', route => membersAvailable ? route.continue() : route.fulfill({ status: 500, json: { error: { message: 'Synthetic assignee failure' } } }));
    await signIn(page, 'IT_STAFF');
    await page.getByRole('button', { name: `Open ${ticket.ticketNumber}`, exact: true }).click();
    await page.getByRole('button', { name: 'Actions Taken', exact: true }).click();
    await page.getByRole('button', { name: 'Add Action' }).click();
    const description = page.getByLabel('Action Description');
    await description.fill('Retain this complete draft across failures');
    await expect(page.getByRole('button', { name: 'Save Action' })).toBeDisabled();
    await expect(page.getByRole('button', { name: 'Retry Assignees' })).toBeVisible();
    membersAvailable = true; await page.getByRole('button', { name: 'Retry Assignees' }).click();
    await expect(page.getByRole('button', { name: 'Save Action' })).toBeEnabled();
    const bodies: { clientRequestId: string }[] = [];
    let status = 400, release!: () => void;
    const gate = new Promise<void>(resolve => { release = resolve; });
    await page.route(`**/api/staff/tickets/${ticket.id}/actions-taken`, async route => {
      bodies.push(route.request().postDataJSON());
      if (status === 201) { await gate; return route.continue(); }
      return route.fulfill({ status, json: { error: { code: status === 422 ? 'INVALID_ACTION_TRANSITION' : status === 400 ? 'VALIDATION_ERROR' : 'INTERNAL_ERROR',
        message: `Synthetic HTTP ${status}`, ...(status === 400 ? { details: [{ field: 'description', message: 'Review the preserved description' }] } : {}) } } });
    });
    for (const failure of [400, 500, 422]) {
      status = failure; await page.getByRole('button', { name: 'Save Action' }).click();
      await expect(page.getByText(`Synthetic HTTP ${failure}`, { exact: true })).toBeVisible();
      await expect(description).toHaveValue('Retain this complete draft across failures');
      if (failure === 400) await expect(description).toHaveAttribute('aria-invalid', 'true');
      await snapshot(page, info, `action-error-${failure}`);
      if (failure === 422) {
        await expect(page.getByRole('button', { name: 'Save Action' })).toBeDisabled();
        await page.getByRole('button', { name: 'Reload Latest' }).click();
        await expect(page.getByRole('button', { name: 'Save Action' })).toBeEnabled();
      }
    }
    status = 201; await page.getByRole('button', { name: 'Save Action' }).click();
    await expect(page.getByRole('button', { name: 'Saving...' })).toBeDisabled();
    await expect(description).toBeDisabled();
    expect(bodies).toHaveLength(4); expect(new Set(bodies.map(body => body.clientRequestId)).size).toBe(1);
    release();
    await expect(page.getByText('Action saved successfully.')).toBeVisible();
    expect(await db.actionTaken.count({ where: { ticketId: ticket.id } })).toBe(1);
  });

